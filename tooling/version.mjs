import { execFileSync, spawn } from "node:child_process";
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));

/** Resolve a build identity once; Git-less image builds must supply the full commit SHA. */
export function resolveVersion(
  env = process.env,
  readGit = () =>
    execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: root,
      encoding: "utf8",
    }).trim(),
) {
  const sha = env.APP_VERSION ?? readGit();
  if (!/^(?:[a-f0-9]{40}|[a-f0-9]{64})$/i.test(sha))
    throw new Error(
      "APP_VERSION must be a full Git SHA (40 or 64 hexadecimal characters)",
    );
  return sha.toLowerCase();
}

/** Persist immutable source constants, shared by browser bundles, Next servers and the worker. */
export function stampVersion(
  sha,
  destination = resolve(
    root,
    "packages/observability/src/build-info.generated.ts",
  ),
) {
  const source = `// Generated by tooling/version.mjs. Do not edit.\nexport const APP_VERSION = ${JSON.stringify(sha)};\nexport const GIT_SHA = ${JSON.stringify(sha)};\n`;
  let current;
  try {
    current = readFileSync(destination, "utf8");
  } catch {
    /* First install. */
  }
  if (current === source) return;
  mkdirSync(dirname(destination), { recursive: true });
  const temporary = `${destination}.${process.pid}.tmp`;
  writeFileSync(temporary, source);
  renameSync(temporary, destination);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const version = resolveVersion();
  stampVersion(version);
  const [command, ...args] = process.argv.slice(2);
  if (command) {
    // Set before Turbo computes hashes, so a new commit cannot restore an old deploy stamp.
    const child = spawn(command, args, {
      stdio: "inherit",
      env: { ...process.env, APP_VERSION: version },
    });
    for (const signal of ["SIGINT", "SIGTERM"])
      process.on(signal, () => child.kill(signal));
    child.on("error", (error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    });
    child.on("exit", (code, signal) => {
      process.exitCode = code ?? (signal ? 1 : 0);
    });
  }
}
